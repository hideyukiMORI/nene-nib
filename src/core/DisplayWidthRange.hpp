// 表示幅が 1 桁でない code point の範囲の表（ADR 0034 の決定 1）。ここに無い code point は
// single である。範囲は昇順で重ならず、隣り合う範囲は幅が違う（下の static_assert が守る）。
//
// 出典: 固定 Vim 9.1（2024 Jan 02）で `strdisplaywidth('a' . nr2char(cp)) - 1` を
// U+0000〜U+10FFFF の全 code point について測った値そのもの（既定の `ambiwidth=single` /
// `encoding=utf-8`・測定は out/issue108-oracle/probe2.py）。Unicode の EastAsianWidth を
// 写すのではなく Vim の答えを正本にするのは、この engine の再現度を守るのが oracle の
// fixture だからである（版がずれたときの差は fixture が見つける・ADR 0034 の「結果」）。
// 単体の `strdisplaywidth(nr2char(cp))` は結合文字に 1 を返すので、基底文字の後ろに
// 置いた形で測っている。Tab（U+0009）は桁の位置で決まるのでこの表には載せない。
// U+0000 だけは `nr2char(0)` が空文字列になって測れないので、同じ形（`^@`）で描かれる
// ほかの制御文字に合わせて wide に入れてある。
// U+0080〜U+009F（C1 制御文字）は Issue #147 で `strdisplaywidth("\x85") == 4` を測り直し、Vim が
// `<85>` と描く 4 桁の hex に入れた（ADR 0034 の補足）。
