"""Generate src/core/HeadingSlugTable.hpp from github-slugger's regex.js (#1869, ADR 0151 stage L3).

A heading's slug (the `#name` a Markdown link points at) drops the code points GitHub's slugger
drops. The upstream is github-slugger 2.0.0, whose `slug()` lowercases the text, removes every
match of one regular expression (`regex.js`, generated by its own script from the Unicode
categories) and turns each U+0020 into `-`. That file is kept as upstream bytes in
third_party/github-slugger/ (CNF-013 pins its SHA-256; this tool pins it again with the version so
that a new file cannot be read by mistake). The JavaScript is never run: this tool reads the
character classes of the expression, decodes the UTF-16 surrogate pairs of the astral alternatives
to code points and writes the closed ranges in ascending order. CNF-010 compares the stored file
with `heading_slug_table_header()` byte for byte (eng/conformance.py), so this file is the one place
the C++ table's form is written.

  python eng/heading-slug-table.py --write   rewrite src/core/HeadingSlugTable.hpp
  python eng/heading-slug-table.py --check   exit 1 when the stored file differs
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = "src/core/HeadingSlugTable.hpp"
SOURCE = "third_party/github-slugger/regex.js"
VERSION = "2.0.0"
SOURCE_SHA256 = "3bcbb3836a4e76f0f343c34d223ddd9eac83cc73a4e2c7a1118ef0829bc9129b"
BANNER = "// 生成物。手で編集しない。python eng/heading-slug-table.py --write"

BACKSLASH = "\\"
EXPRESSION = re.compile(r"export const regex = /(.*)/g\n")
# An astral alternative is a high surrogate (one, or a class of them) followed by a class of lows.
ASTRAL = re.compile(r"(\\uD[89AB][0-9A-F]{2}|\[[^\]]*\])(\[[^\]]*\])")


def source_text() -> str:
    data = (ROOT / SOURCE).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(f"{SOURCE}: sha256 {digest} is not github-slugger {VERSION} ({SOURCE_SHA256})")
    return data.decode("ascii")


def unit_at(text: str, at: int) -> tuple[int, int]:
    """One UTF-16 code unit of a character class at `at` and the index after it."""
    if text[at] != BACKSLASH:
        return ord(text[at]), at + 1
    kind = text[at + 1]
    if kind == "u":
        return int(text[at + 2:at + 6], 16), at + 6
    if kind == "x":
        return int(text[at + 2:at + 4], 16), at + 4
    if kind == "0":
        return 0, at + 2
    return ord(kind), at + 2


def class_ranges(text: str) -> list[tuple[int, int]]:
    """The closed ranges of code units of one `[...]` class (no negation, no nested escapes)."""
    if not (text.startswith("[") and text.endswith("]")) or text.startswith("[^"):
        raise ValueError(f"not a plain character class: {text[:30]}")
    inner = text[1:-1]
    ranges = []
    at = 0
    while at < len(inner):
        first, at = unit_at(inner, at)
        last = first
        if at + 1 < len(inner) and inner[at] == "-":
            last, at = unit_at(inner, at + 1)
        if last < first:
            raise ValueError(f"descending range in {text[:30]}")
        ranges.append((first, last))
    return ranges


def removed_ranges() -> list[tuple[int, int]]:
    """The code points github-slugger removes, as merged closed ranges in ascending order."""
    found = EXPRESSION.search(source_text())
    if found is None:
        raise ValueError(f"{SOURCE}: the exported expression is not found")
    alternatives = found.group(1).split("|")
    points = []
    for first, last in class_ranges(alternatives[0]):
        if first <= 0xDFFF and last >= 0xD800:
            raise ValueError("the BMP class names a surrogate")
        points.append((first, last))
    for alternative in alternatives[1:]:
        found_pair = ASTRAL.fullmatch(alternative)
        if found_pair is None:
            raise ValueError(f"not a surrogate pair alternative: {alternative[:30]}")
        high_part, low_part = found_pair.group(1), found_pair.group(2)
        highs = class_ranges(high_part) if high_part.startswith("[") else [(unit_at(high_part, 0)[0],) * 2]
        lows = class_ranges(low_part)
        if not all(0xD800 <= first <= last <= 0xDBFF for first, last in highs) or \
                not all(0xDC00 <= first <= last <= 0xDFFF for first, last in lows):
            raise ValueError(f"not a surrogate pair alternative: {alternative[:30]}")
        for high_first, high_last in highs:
            for high in range(high_first, high_last + 1):
                base = 0x10000 + ((high - 0xD800) << 10)
                points.extend((base + first - 0xDC00, base + last - 0xDC00) for first, last in lows)
    merged: list[tuple[int, int]] = []
    for first, last in sorted(points):
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(last, merged[-1][1]))
        else:
            merged.append((first, last))
    return merged


def heading_slug_table_header() -> str:
    """The whole of src/core/HeadingSlugTable.hpp."""
    ranges = removed_ranges()
    rows = "\n".join(f"    {{0x{first:04X}, 0x{last:04X}}}," for first, last in ranges)
    return ("// clang-format off\n"
            f"{BANNER}\n"
            f"// github-slugger {VERSION} の regex.js（sha256 {SOURCE_SHA256}）が消す code point の"
            "閉区間（昇順・重ならず隣り合わない）\n"
            "#pragma once\n"
            "\n"
            "#include <array>\n"
            "#include <utility>\n"
            "\n"
            "namespace nenenib::core\n"
            "{\n"
            "inline constexpr std::array<std::pair<char32_t, char32_t>, "
            f"{len(ranges)}> heading_slug_removed_ranges{{{{\n"
            f"{rows}\n"
            "}};\n"
            "} // namespace nenenib::core\n"
            "// clang-format on\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help=f"rewrite {TARGET}")
    mode.add_argument("--check", action="store_true", help=f"exit 1 when {TARGET} differs")
    arguments = parser.parse_args()
    target = ROOT / TARGET
    content = heading_slug_table_header().encode("utf-8")
    if arguments.write:
        target.write_bytes(content)
        return 0
    if target.is_file() and target.read_bytes() == content:
        return 0
    print(f"{TARGET} differs from the generated table; run python eng/heading-slug-table.py --write",
          file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
